-- Role mapping
-- admin/president: ALL
-- vp, gen_sec, ags, pro: executive/president memo, treasurer_records
-- fin_sec: ledger (transactions)
-- treasurer: treasurer_records
-- src: src memo
-- elecom: elecom memo

-- 1. Create Roles Table
CREATE TABLE IF NOT EXISTS public.user_roles (
  id uuid not null default gen_random_uuid(),
  user_email text not null,
  role text not null,
  created_at timestamp with time zone null default now(),
  constraint user_roles_pkey primary key (id),
  constraint user_roles_user_email_key unique (user_email)
) TABLESPACE pg_default;

-- Enable RLS on roles
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;

-- Helper function to get the current user's role
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT role FROM public.user_roles WHERE user_email = (auth.jwt() ->> 'email') LIMIT 1;
$$;

-- RLS for user_roles
CREATE POLICY "Allow authenticated to read roles" ON public.user_roles 
FOR SELECT TO authenticated USING (true);

CREATE POLICY "Allow admins to manage roles" ON public.user_roles 
FOR ALL TO authenticated USING (public.get_user_role() IN ('admin', 'president'));

-- 2. Memo Table
CREATE TABLE IF NOT EXISTS public.memo (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  date date null,
  reference text not null,
  content text null,
  head text null default ''::text,
  is_published boolean not null default true,
  created_by text null,
  last_edited_by text null default 'null'::text,
  type text null default 'executive'::text,
  constraint memo_pkey primary key (id),
  constraint memo_reference_key unique (reference)
) TABLESPACE pg_default;

ALTER TABLE public.memo ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public can read published memos" ON public.memo 
FOR SELECT USING (is_published = true);

CREATE POLICY "Role based memo management" ON public.memo 
FOR ALL TO authenticated USING (
  public.get_user_role() IN ('admin', 'president')
  OR
  (public.get_user_role() IN ('vp', 'gen_sec', 'ags', 'pro') AND type IN ('executive', 'president'))
  OR
  (public.get_user_role() = 'src' AND type = 'src')
  OR
  (public.get_user_role() = 'elecom' AND type = 'elecom')
) WITH CHECK (
  public.get_user_role() IN ('admin', 'president')
  OR
  (public.get_user_role() IN ('vp', 'gen_sec', 'ags', 'pro') AND type IN ('executive', 'president'))
  OR
  (public.get_user_role() = 'src' AND type = 'src')
  OR
  (public.get_user_role() = 'elecom' AND type = 'elecom')
);

